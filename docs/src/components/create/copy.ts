export function optionLabel(option: { value: string; label: string }, lang: string) {
  const translated = optionNames[option.value];
  if (!translated) return option.label;
  switch (lang) {
    case "ko":
      return translated[0];
    case "ja":
      return translated[1];
    case "zh":
      return translated[2];
    default:
      return option.label;
  }
}
